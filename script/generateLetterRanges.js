// @ts-check
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const parserSource = await readFile(path.join(root, 'src/parser.c'), 'utf8');
const lexTable = parseLexTable(parserSource);
const { startState, loopState } = findTemplateNameStates(lexTable);

const tables = [
  formatRangeTable('LETTER_RANGES', lexTable, (cls) => acceptsTemplateNameFrom(lexTable, startState, cls)),
  formatRangeTable('NAME_PART_RANGES', lexTable, (cls) => transitionsToState(lexTable, loopState, cls, loopState)),
].join('');

await writeFile(
  path.join(root, 'src/letter_ranges.h'),
  `// Generated by script/generateLetterRanges.js from the parser's template-name lex table.
#ifndef TREE_SITTER_KOTLIN_LETTER_RANGES_H_
#define TREE_SITTER_KOTLIN_LETTER_RANGES_H_

#include <stdint.h>

${tables}#endif
`
);

/**
 * @param {string} source
 */
function parseLexTable(source) {
  const symbolMatch = /\baux_sym__template_name_token1\s*=\s*(\d+)/.exec(source);
  assert.ok(symbolMatch?.[1], 'Missing aux_sym__template_name_token1 in src/parser.c');
  const tableMatch = /static const uint16_t ts_lex_table\[\] = \{([\s\S]*?)\};/.exec(source);
  assert.ok(tableMatch?.[1], 'Missing ts_lex_table in src/parser.c');
  const words = Uint16Array.from((tableMatch[1].match(/\d+/g) ?? []).map(Number));
  const stateCount = words[2] ?? 0;
  const unicodeRanges = words[5] ?? 0;
  const wideBase = ((words[6] ?? 0) & 0x40_00) !== 0;
  const combLen = readU32(words, 7);
  const extTransLen = readU32(words, 9);
  const unicodeEndsOffset = 141;
  const stateMetaOffset = unicodeEndsOffset + unicodeRanges * 3;
  const combOffset = stateMetaOffset + stateCount * (wideBase ? 5 : 4);
  const extTransOffset = combOffset + combLen * 2;
  return {
    words,
    targetSymbol: Number(symbolMatch[1]),
    stateCount,
    unicodeRanges,
    wideBase,
    asciiClassOffset: 13,
    unicodeEndsOffset,
    unicodeClassesOffset: unicodeEndsOffset + unicodeRanges * 2,
    stateMetaOffset,
    combOffset,
    extTransOffset,
    extAcceptOffset: extTransOffset + extTransLen,
  };
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 */
function findTemplateNameStates(table) {
  const underscoreClass = table.words[table.asciiClassOffset + 0x5f] ?? 0xff_ff;
  const digitClass = table.words[table.asciiClassOffset + 0x30] ?? 0xff_ff;
  const spaceClass = table.words[table.asciiClassOffset + 0x20] ?? 0xff_ff;
  let fallback;
  for (let state = 0; state < table.stateCount; state++) {
    const loopState = matchTemplateStartState(table, state, underscoreClass, digitClass);
    if (loopState === undefined) continue;
    if (lookupAction(table, state, spaceClass) === 0) {
      return { startState: state, loopState };
    }
    fallback ??= { startState: state, loopState };
  }
  assert.ok(fallback, 'Missing template-name lex states in ts_lex_table');
  return fallback;
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} state
 * @param {number} underscoreClass
 * @param {number} digitClass
 */
function matchTemplateStartState(table, state, underscoreClass, digitClass) {
  if (acceptedSymbol(table, stateMeta(table, state).acc) === table.targetSymbol) return;
  if (acceptsTemplateNameFrom(table, state, digitClass)) return;
  const action = lookupAction(table, state, underscoreClass);
  if (action === 0 || isSkipAction(table, action)) return;
  const next = actionNextState(table, action);
  if (acceptedSymbol(table, stateMeta(table, next).acc) !== table.targetSymbol) return;
  return transitionsToState(table, next, underscoreClass, next) && transitionsToState(table, next, digitClass, next)
    ? next
    : undefined;
}

/**
 * @param {string} name
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {(cls: number) => boolean} predicate
 */
function formatRangeTable(name, table, predicate) {
  /** @type {string[]} */
  const lines = [`static const uint32_t ${name}[][2] = {`];
  let runStart = -1;
  let prevEnd = -1;
  for (let index = 0; index < table.unicodeRanges; index++) {
    const lo = index === 0 ? 0x80 : readU32(table.words, table.unicodeEndsOffset + (index - 1) * 2) + 1;
    const hi = readU32(table.words, table.unicodeEndsOffset + index * 2);
    const cls = table.words[table.unicodeClassesOffset + index] ?? 0xff_ff;
    if (predicate(cls)) {
      if (runStart < 0) runStart = lo;
      prevEnd = hi;
    } else if (runStart >= 0) {
      lines.push(`    {0x${runStart.toString(16)}, 0x${prevEnd.toString(16)}},`);
      runStart = -1;
    }
  }
  if (runStart >= 0) {
    lines.push(`    {0x${runStart.toString(16)}, 0x${prevEnd.toString(16)}},`);
  }
  lines.push('};', '', '');
  return lines.join('\n');
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} state
 * @param {number} cls
 */
function acceptsTemplateNameFrom(table, state, cls) {
  const action = lookupAction(table, state, cls);
  if (action === 0 || isSkipAction(table, action)) return false;
  return acceptedSymbol(table, stateMeta(table, actionNextState(table, action)).acc) === table.targetSymbol;
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} state
 * @param {number} cls
 * @param {number} expectedNext
 */
function transitionsToState(table, state, cls, expectedNext) {
  const action = lookupAction(table, state, cls);
  return action !== 0 && !isSkipAction(table, action) && actionNextState(table, action) === expectedNext;
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} state
 * @param {number} cls
 */
function lookupAction(table, state, cls) {
  const meta = stateMeta(table, state);
  if (meta.tmpl === 0 || cls === 0xff_ff) return 0;
  const offset = table.combOffset + (meta.base + cls) * 2;
  return table.words[offset] === meta.tmpl ? (table.words[offset + 1] ?? 0) : meta.def;
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} state
 */
function stateMeta(table, state) {
  if (!table.wideBase) {
    const offset = table.stateMetaOffset + state * 4;
    return {
      base: table.words[offset] ?? 0,
      tmpl: table.words[offset + 1] ?? 0,
      def: table.words[offset + 2] ?? 0,
      acc: table.words[offset + 3] ?? 0,
    };
  }
  const offset = table.stateMetaOffset + state * 5;
  return {
    base: readU32(table.words, offset),
    tmpl: table.words[offset + 2] ?? 0,
    def: table.words[offset + 3] ?? 0,
    acc: table.words[offset + 4] ?? 0,
  };
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} action
 */
function isSkipAction(table, action) {
  if (action < 0x80_00) return (action & 0x40_00) !== 0;
  return ((table.words[table.extTransOffset + (action & 0x7f_ff) + 1] ?? 0) & 0x80_00) !== 0;
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} action
 */
function actionNextState(table, action) {
  if (action < 0x80_00) return (action & 0x1f_ff) - 1;
  return table.words[table.extTransOffset + (action & 0x7f_ff)] ?? 0;
}

/**
 * @param {ReturnType<typeof parseLexTable>} table
 * @param {number} accept
 */
function acceptedSymbol(table, accept) {
  if (accept === 0) return -1;
  if (accept < 0x80_00) return (accept & 0x3f_ff) - 1;
  let offset = table.extAcceptOffset + (accept & 0x7f_ff);
  const flags = table.words[offset++] ?? 0;
  const fallbackSymbol = flags & 1 ? (table.words[offset] ?? -1) : -1;
  if (flags & 1) offset += 4;
  if (flags & 2) return fallbackSymbol;
  return flags & 4 ? (table.words[offset] ?? -1) : -1;
}

/**
 * @param {Uint16Array} words
 * @param {number} offset
 */
function readU32(words, offset) {
  return ((words[offset] ?? 0) | ((words[offset + 1] ?? 0) << 16)) >>> 0;
}
